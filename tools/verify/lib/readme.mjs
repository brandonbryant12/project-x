// Renders docs/feature-map/README.md from features.json, so the human view and
// the machine-readable map cannot drift (`pnpm verify check` compares them).
// The output is written to be stable under the repository's formatter.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  MAP_PATH,
  README_PATH,
  TEST_KINDS,
  commandsFor,
  describeBrowser,
  loadMap,
} from './map.mjs';
import { ROOT } from './paths.mjs';
import { apiGroups } from './repo.mjs';

const FROM_README = '../../';
const code = (s) => `\`${s}\``;
const link = (path) => `[${path}](${FROM_README}${path})`;
const STATE_WORDS = {
  built: 'built',
  behind_switch: 'built, behind a switch',
  api_only: 'built, API only',
  deferred: 'deferred',
  not_built: 'not built',
};

/** A Markdown table with padded columns, as the formatter would print it. */
const table = (header, rows) => {
  const widths = header.map((h, i) => Math.max(h.length, 3, ...rows.map((r) => r[i].length)));
  const line = (cells) => `| ${cells.map((c, i) => c.padEnd(widths[i])).join(' | ')} |`;
  return [line(header), line(widths.map((w) => '-'.repeat(w))), ...rows.map(line)].join('\n');
};

const checksOf = (feature) => {
  const kinds = commandsFor(feature)
    .map((c) => c.kind)
    .filter((k) => k !== 'other');
  return kinds.length > 0 ? kinds.join(', ') : 'none';
};

const bullet = (label, values) => (values.length > 0 ? [`- ${label}: ${values.join(', ')}`] : []);

const featureSection = (feature, groups) => {
  const c = feature.code ?? {};
  const endpoint = (e) => {
    const [group, name] = e.split('.');
    const route = groups.get(group)?.endpoints.get(name);
    return route ? `${code(e)} (${code(route)})` : code(e);
  };
  const lines = [`### ${feature.id}`, '', `**${feature.name}.** ${feature.summary}`, ''];
  lines.push(`- State: ${STATE_WORDS[feature.state] ?? feature.state}`);
  if (feature.switch) lines.push(`- Switch: ${code(feature.switch)}`);
  if (feature.reason) lines.push(`- Why: ${feature.reason}`);
  if (feature.recordedIn) lines.push(`- Recorded in: ${link(feature.recordedIn)}`);
  lines.push(...bullet('Personas', feature.personas ?? []));
  lines.push(...bullet('May', feature.permissions?.may ?? []));
  lines.push(...bullet('Refused', feature.permissions?.refused ?? []));
  lines.push(...bullet('States to check', feature.states ?? []));
  lines.push(...bullet('Web', (c.web ?? []).map(code)));
  lines.push(...bullet('Server', (c.server ?? []).map(code)));
  lines.push(...bullet('API', (c.api ?? []).map(endpoint)));
  lines.push(...bullet('Domain', (c.domain ?? []).map(code)));
  lines.push(...bullet('Other code', (c.other ?? []).map(code)));
  lines.push(...bullet('Tables', (c.tables ?? []).map(code)));
  lines.push(...bullet('Agent skills', (feature.skills ?? []).map(link)));
  if (feature.qa) lines.push(`- QA playbook: ${link(feature.qa)}`);
  for (const kind of TEST_KINDS)
    lines.push(...bullet(`Tests (${kind})`, (feature.tests?.[kind] ?? []).map(code)));
  const browser = describeBrowser(feature);
  if (browser) lines.push(`- Browser check: ${browser}`);
  const commands = commandsFor(feature);
  if (commands.length > 0) {
    lines.push('', 'Verify:', '', '```sh', ...commands.map((x) => x.command), '```');
  }
  const gaps = feature.gaps ?? [];
  if (gaps.length > 0) lines.push('', 'Gaps:', '', ...gaps.map((g) => `- ${g}`));
  return lines.join('\n');
};

export const renderReadme = (map, groups = apiGroups()) => {
  const rows = map.features.map((f) => [
    `[${f.id}](#${f.id})`,
    f.name,
    STATE_WORDS[f.state] ?? f.state,
    checksOf(f),
  ]);
  return `${[
    '# Feature map',
    '',
    `<!-- Generated by \`pnpm verify readme\` from features.json. Edit that file, not this one. -->`,
    '',
    `Every product feature, who can use it, where its code lives, the agent instructions and QA playbook that apply, the tests that protect it and the commands that verify it end to end. The source is [features.json](features.json); this page is generated from it. "Skills" here means agent instructions under ${code('.claude/skills/')}, not the product's skill catalog.`,
    '',
    '## How to use it',
    '',
    `- Find a feature: ${code('pnpm verify list')}, ${code('pnpm verify list --state built --persona "Maya Chen"')}, ${code('pnpm verify show <id>')}.`,
    `- Choose checks for a change: ${code('pnpm verify which --changed')} (against ${code('main')}) or ${code('pnpm verify which <path...>')}.`,
    `- Run the isolated QA environment: ${code('pnpm verify env build')}, ${code('pnpm verify env seed')}, ${code('pnpm verify env start')}, then ${code('pnpm verify env stop')}. It serves the API and the built web app on port 4410 with its own PGlite data under ${code('.data/qa')}.`,
    `- Verify: ${code('pnpm verify run <id...> --kind tests|api|browser')}. Each run writes a JSON result and a short summary under ${code('.data/verify/runs')} (or ${code('--out <dir>')}) and exits non-zero when a check failed or errored.`,
    `- Keep it current: ${code('pnpm verify check')} runs in ${code('pnpm check')} and CI. How to update the map with a feature change: ${link('.claude/skills/feature-map/SKILL.md')}.`,
    '',
    '## Evidence kinds',
    '',
    `- ${code('tests')}: the feature's test files with Vitest (domain tables, PGlite scenarios, database integrity). Automated evidence.`,
    `- ${code('api')}: journey checks in ${code('tools/verify/journeys')} against a running server, signed in as seeded personas through the dev sign-in. Real-server evidence without a browser.`,
    `- ${code('browser')}: the screenshot spec (${code('apps/web/e2e/screenshots.spec.ts')}) narrowed to the feature's routes and personas, including the no-sideways-scroll check. Rendered evidence: the PNGs prove pages render, and a person or agent still has to open and judge them.`,
    `- Every check ends as ${code('passed')}, ${code('failed')}, ${code('skipped')} (with the reason, for example no server answering) or ${code('error')}. Skipped is never counted as passed.`,
    '',
    '## Features',
    '',
    table(['Feature', 'Name', 'State', 'Checks'], rows),
    '',
    '## Details',
    '',
    map.features.map((f) => featureSection(f, groups)).join('\n\n'),
  ].join('\n')}\n`;
};

export const readmeCommand = () => {
  writeFileSync(join(ROOT, README_PATH), renderReadme(loadMap()));
  process.stdout.write(`wrote ${README_PATH} from ${MAP_PATH}\n`);
  return 0;
};
